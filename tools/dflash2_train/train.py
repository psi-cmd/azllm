import itertools
import json
import math
import os
import random
import shlex
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from features import FeatureCache, FeaturePool, FeatureServer  # noqa: E402
from gguf_target import build_frozen_modules  # noqa: E402

# Published z-lab/Qwen3.8-27B-DFlash2 geometry (matches models/drafters/*DFlash2*.gguf).
DRAFT_DEFAULTS = dict(
    layers=5, heads=32, kv_heads=8, head_dim=128, block_size=8, sliding_window=2048,
    mask_token_id=248070, target_layer_ids=[5, 19, 33, 47, 61],
    conv_kernel_size=2, conv_group_size=16, selector_rank=256, selector_top_k=16,
)


def parse_args():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--automodel", required=True, help="checkout of NVIDIA-NeMo/Automodel (contains nemo_automodel/)")
    ap.add_argument("--target-gguf", required=True)
    ap.add_argument("--data", required=True, help="JSONL training samples")
    ap.add_argument("--out", required=True)
    # feature source
    ap.add_argument("--features-bin", help="tqfeatures executable (omit to replay --feature-cache only)")
    ap.add_argument("--drafter-gguf", help="any DFlash2 GGUF for the target (only its layer list is used)")
    ap.add_argument("--feature-servers", type=int, default=1, help="tqfeatures processes (each loads the target)")
    ap.add_argument("--feature-context", type=int, default=4096)
    ap.add_argument("--feature-args", default="", help="extra engine options for tqfeatures, e.g. '--prefill-int8 off'")
    ap.add_argument("--feature-cache", help="directory to store/replay feature frames")
    ap.add_argument("--dump-only", action="store_true", help="fill --feature-cache for --data and exit")
    # draft
    ap.add_argument("--init", help="HF drafter dir (safetensors + config.json) to warm start from")
    ap.add_argument("--draft-layers", type=int, default=DRAFT_DEFAULTS["layers"])
    ap.add_argument("--attention-backend", default="sdpa", choices=["sdpa", "flex_attention", "eager"])
    ap.add_argument("--max-seq", type=int, default=3072, help="truncate samples to this many tokens")
    ap.add_argument("--num-anchors", type=int, default=64)
    ap.add_argument("--loss-gamma", type=float, default=4.0)
    ap.add_argument("--selector-loss-weight", type=float, default=1.0)
    # optimisation
    ap.add_argument("--steps", type=int, default=1000, help="optimizer steps")
    ap.add_argument("--grad-accum", type=int, default=8)
    ap.add_argument("--lr", type=float, default=6e-4)
    ap.add_argument("--warmup-ratio", type=float, default=0.04)
    ap.add_argument("--min-lr-ratio", type=float, default=0.1)
    ap.add_argument("--weight-decay", type=float, default=0.0)
    ap.add_argument("--max-grad-norm", type=float, default=1.0)
    ap.add_argument("--epochs", type=int, default=0, help="stop after this many data passes (0: loop until --steps)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--log-every", type=int, default=10)
    ap.add_argument("--save-every", type=int, default=500)
    return ap.parse_args()


def read_records(path: str, max_seq: int, epochs: int, seed: int):
    """Yield (input_ids int64, loss_mask f32), shuffled per epoch; epochs=0 loops forever."""
    rows = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            if "input_ids" in r:
                ids = r["input_ids"]
                mask = r.get("loss_mask") or [1] * len(ids)
            else:
                ids = list(r["prompt_ids"]) + list(r["response_ids"])
                mask = [0] * len(r["prompt_ids"]) + [1] * len(r["response_ids"])
            if len(ids) != len(mask):
                raise ValueError(f"{path}: input_ids/loss_mask length mismatch")
            ids, mask = ids[:max_seq], mask[:max_seq]
            if sum(mask) >= 2:
                rows.append((np.asarray(ids, np.int64), np.asarray(mask, np.float32)))
    if not rows:
        raise ValueError(f"{path}: no usable samples")
    rng = random.Random(seed)
    for _ in itertools.count() if epochs == 0 else range(epochs):
        order = list(range(len(rows)))
        rng.shuffle(order)
        for i in order:
            yield rows[i]


def build_draft(args, target_cfg, torch):
    from transformers.models.qwen3.configuration_qwen3 import Qwen3Config
    from nemo_automodel.components.speculative.dflash.draft_qwen3_dflash2 import Qwen3DFlash2DraftModel

    d = DRAFT_DEFAULTS
    if args.init:
        cfg = Qwen3Config.from_pretrained(args.init)
    else:
        L = args.draft_layers
        cfg = Qwen3Config(
            vocab_size=target_cfg["vocab_size"],
            hidden_size=target_cfg["hidden_size"],
            intermediate_size=17408,
            num_hidden_layers=L,
            num_attention_heads=d["heads"],
            num_key_value_heads=d["kv_heads"],
            head_dim=d["head_dim"],
            rms_norm_eps=target_cfg["rms_norm_eps"],
            max_position_embeddings=262144,
            rope_theta=10_000_000.0,
            tie_word_embeddings=False,
            attention_bias=False,
            hidden_act="silu",
        )
        # rope_parameters is the newer transformers spelling; set both for readers on either side.
        cfg.rope_parameters = {"rope_theta": 10_000_000.0, "rope_type": "default"}
        cfg.architectures = ["Qwen3DFlash2DraftModel"]
        cfg.layer_types = ["sliding_attention"] * L
        cfg.sliding_window = d["sliding_window"]
        cfg.use_sliding_window = True
        cfg.max_window_layers = L
        cfg.is_causal = False
        cfg.num_target_layers = target_cfg["num_layers"]
        cfg.block_size = d["block_size"]
        cfg.dflash_config = {
            "block_size": d["block_size"],
            "mask_token_id": d["mask_token_id"],
            "target_layer_ids": d["target_layer_ids"],
            "output_multiplier": 1.0,
            "final_logit_softcapping": None,
            "input_embedding_scale": 1.0,
            "conv_kernel_size": d["conv_kernel_size"],
            "conv_group_size": d["conv_group_size"],
            "selector_rank": d["selector_rank"],
            "selector_top_k": d["selector_top_k"],
        }
    cfg._attn_implementation = args.attention_backend
    model = Qwen3DFlash2DraftModel(cfg)
    if args.init:
        from safetensors.torch import load_file

        sd = {}
        for shard in sorted(Path(args.init).glob("*.safetensors")):
            sd.update(load_file(str(shard)))
        missing, unexpected = model.load_state_dict(sd, strict=False)
        print(f"init from {args.init}: missing={missing} unexpected={unexpected}", flush=True)
    return model, cfg


def save(model, cfg, out_dir: Path, torch):
    from safetensors.torch import save_file

    out_dir.mkdir(parents=True, exist_ok=True)
    sd = {k: v.detach().to(torch.bfloat16).contiguous().cpu() for k, v in model.state_dict().items()}
    save_file(sd, str(out_dir / "model.safetensors"), metadata={"format": "pt"})
    d = cfg.to_dict()
    d["architectures"] = ["DFlash2DraftModel"]  # name convert-dflash2-ref.py / the published drafters use
    d["rope_parameters"] = getattr(cfg, "rope_parameters", None) or {"rope_theta": 10_000_000.0, "rope_type": "default"}
    (out_dir / "config.json").write_text(json.dumps(d, indent=2, default=str))
    print(f"saved {out_dir}", flush=True)


def lr_at(step: int, args) -> float:
    warm = max(1, int(args.steps * args.warmup_ratio))
    if step < warm:
        return args.lr * (step + 1) / warm
    t = (step - warm) / max(1, args.steps - warm)
    return args.lr * (args.min_lr_ratio + (1 - args.min_lr_ratio) * 0.5 * (1 + math.cos(math.pi * min(1.0, t))))


def make_pool(args):
    cache = FeatureCache(args.feature_cache) if args.feature_cache else None
    servers = []
    if args.features_bin:
        if not args.drafter_gguf:
            raise SystemExit("--features-bin needs --drafter-gguf")
        out = Path(args.out)
        out.mkdir(parents=True, exist_ok=True)
        for i in range(args.feature_servers):
            cmd = [args.features_bin, "--model", args.target_gguf, "-md", args.drafter_gguf,
                   "--context", str(args.feature_context)] + shlex.split(args.feature_args)
            servers.append(FeatureServer(cmd, log_path=str(out / f"tqfeatures.{i}.log")))
    elif not cache:
        raise SystemExit("need --features-bin or --feature-cache")
    return FeaturePool(servers, cache), servers


def _stub_hf_datasets():
    """nemo_automodel's packed_sequence imports HF ``datasets`` at module level for packing helpers this
    trainer never calls; when the package is absent (e.g. the BW container), stand in a placeholder."""
    try:
        import datasets  # noqa: F401
    except ImportError:
        import importlib.machinery
        import types

        import transformers  # noqa: F401  -- probe for `datasets` before the stub exists, so it reads absent

        class _Unavailable:
            def __init__(self, *a, **k):
                raise ImportError("HF datasets is not installed (stubbed by dflash2_train)")

        class _Stub(types.ModuleType):
            def __getattr__(self, name):
                if name.startswith("__"):
                    raise AttributeError(name)
                return _Unavailable

        stub = _Stub("datasets")
        stub.__spec__ = importlib.machinery.ModuleSpec("datasets", None)
        sys.modules["datasets"] = stub


def _skip_package_inits(root: str, packages: list[str]):
    """Register packages by path without running their ``__init__`` (which import unrelated recipes).

    The DFlash modules only need ``datasets.llm.packed_sequence``; the package inits pull in every dataset
    recipe and their dependencies.
    """
    import types

    for name in packages:
        if name in sys.modules:
            continue
        mod = types.ModuleType(name)
        mod.__path__ = [str(Path(root, *name.split(".")))]
        sys.modules[name] = mod


def main():
    args = parse_args()
    sys.path.insert(0, args.automodel)
    _stub_hf_datasets()
    _skip_package_inits(args.automodel, [
        "nemo_automodel.components.datasets",
        "nemo_automodel.components.datasets.llm",
        "nemo_automodel.components.speculative.dflash",  # its init also imports the Kimi K3 draft
    ])
    pool, servers = make_pool(args)
    try:
        if args.dump_only:
            n = 0
            t0 = time.time()
            toks = 0
            for s in pool.run(read_records(args.data, args.max_seq, 1, args.seed)):
                n += 1
                toks += len(s.input_ids)
                if n % 20 == 0:
                    print(f"dumped {n} samples, {toks / (time.time() - t0):.0f} tok/s", flush=True)
            print(f"dumped {n} samples ({toks} tokens) to {args.feature_cache}")
            return
        train(args, pool)
    finally:
        for s in servers:
            s.close()


def train(args, pool):
    import torch
    from nemo_automodel.components.speculative.dflash.dflash2_core import DFlash2TrainerModule

    torch.manual_seed(args.seed)
    dev = torch.device(args.device)
    t0 = time.time()
    embed, head, tcfg = build_frozen_modules(args.target_gguf, torch.bfloat16, dev)
    print(f"frozen embed/head from {args.target_gguf} in {time.time() - t0:.0f}s: {tcfg}", flush=True)

    draft, cfg = build_draft(args, tcfg, torch)
    # FP32 master weights (AdamW state alongside), BF16 autocast for compute.
    draft = draft.to(device=dev, dtype=torch.float32)
    n_params = sum(p.numel() for p in draft.parameters())
    print(f"draft: {n_params / 1e9:.3f}B params, {cfg.num_hidden_layers} layers", flush=True)

    d = cfg.dflash_config
    trainer = DFlash2TrainerModule(
        draft_model=draft,
        target_lm_head=head,
        target_embed_tokens=embed,
        mask_token_id=int(d["mask_token_id"]),
        block_size=int(d["block_size"]),
        attention_backend=args.attention_backend,
        num_anchors=args.num_anchors,
        loss_decay_gamma=args.loss_gamma,
        selector_loss_weight=args.selector_loss_weight,
        sliding_window=getattr(cfg, "sliding_window", None),
    ).to(dev)

    opt = torch.optim.AdamW(
        [p for p in draft.parameters() if p.requires_grad],
        lr=args.lr, betas=(0.9, 0.95), weight_decay=args.weight_decay, fused=dev.type == "cuda",
    )

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "args.json").write_text(json.dumps(vars(args), indent=2))
    metrics_f = open(out / "metrics.jsonl", "a")

    stream = pool.run(read_records(args.data, args.max_seq, args.epochs, args.seed))
    step, micro = 0, 0
    win = {"loss": 0.0, "base_loss": 0.0, "sel_loss": 0.0, "acc_tok": 0.0, "tok": 0.0,
           "al_sum": 0.0, "blocks": 0.0, "base_al_sum": 0.0, "recall": 0.0, "seq_tok": 0}
    t_win = time.time()
    draft.train()
    for sample in stream:
        ids = torch.from_numpy(np.ascontiguousarray(sample.input_ids)).to(dev).unsqueeze(0)
        mask = torch.from_numpy(np.ascontiguousarray(sample.loss_mask)).to(dev).unsqueeze(0)
        hid = torch.from_numpy(np.array(sample.hidden, dtype=np.uint16).view(np.int16)).to(dev)  # copy: frames may be read-only
        hid = hid.view(torch.bfloat16).unsqueeze(0)
        with torch.autocast(device_type=dev.type, dtype=torch.bfloat16):
            m = trainer(input_ids=ids, hidden_states=hid, loss_mask=mask)
        (m.loss / args.grad_accum).backward()
        micro += 1
        vt = float(m.valid_tokens)
        win["loss"] += m.loss.item()
        win["base_loss"] += m.base_loss.item()
        win["sel_loss"] += m.selector_loss.item()
        win["acc_tok"] += float(m.correct_tokens)
        win["tok"] += vt
        win["al_sum"] += float(m.accept_len_sum)
        win["base_al_sum"] += float(m.base_accept_len_sum)
        win["blocks"] += float(m.valid_blocks)
        win["recall"] += float(m.candidate_recall) * vt
        win["seq_tok"] += ids.shape[1]
        if micro % args.grad_accum:
            continue

        lr = lr_at(step, args)
        for g in opt.param_groups:
            g["lr"] = lr
        gnorm = torch.nn.utils.clip_grad_norm_(draft.parameters(), args.max_grad_norm)
        opt.step()
        opt.zero_grad(set_to_none=True)
        step += 1

        if step % args.log_every == 0 or step == args.steps:
            k = args.log_every * args.grad_accum
            dt = time.time() - t_win
            rec = {
                "step": step, "lr": lr, "grad_norm": float(gnorm),
                "loss": win["loss"] / k, "base_loss": win["base_loss"] / k, "selector_loss": win["sel_loss"] / k,
                "accuracy": win["acc_tok"] / max(1, win["tok"]),
                "accept_len": win["al_sum"] / max(1, win["blocks"]),
                "base_accept_len": win["base_al_sum"] / max(1, win["blocks"]),
                "candidate_recall": win["recall"] / max(1, win["tok"]),
                "seq_tok_per_s": win["seq_tok"] / dt,
                "mem_gb": torch.cuda.max_memory_allocated() / 2**30 if dev.type == "cuda" else 0.0,
            }
            print(" ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}" for k, v in rec.items()), flush=True)
            metrics_f.write(json.dumps(rec) + "\n")
            metrics_f.flush()
            win = dict.fromkeys(win, 0.0)
            t_win = time.time()
        if args.save_every and step % args.save_every == 0:
            save(draft, cfg, out / f"step_{step}", torch)
        if step >= args.steps:
            break
    save(draft, cfg, out / "final", torch)


if __name__ == "__main__":
    main()

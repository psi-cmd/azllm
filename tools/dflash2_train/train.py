#!/usr/bin/env python3
"""DFlash2 drafter training on azllm target features.

The draft model and loss are the unmodified upstream NeMo Automodel modules
(``Qwen3DFlash2DraftModel`` + ``DFlash2TrainerModule``). What changes is where the target side
comes from:
  * context features: streamed from ``tqfeatures`` (azllm, quantized target on the same card),
    bit-identical to what the drafter sees at inference time;
  * frozen ``embed_tokens`` / ``lm_head``: dequantized from the same target GGUF.

Data: JSONL, one sample per line, either
  {"input_ids": [...], "loss_mask": [...]}           (loss_mask 1 = supervised token), or
  {"prompt_ids": [...], "response_ids": [...]}       (response supervised).
Responses should be generated by the target itself (teacher forcing on the target's own outputs).

Output: ``OUT/step_N/`` (and ``OUT/final/``) with ``model.safetensors`` + ``config.json`` in the
HF layout ``convert-dflash2-ref.py`` turns into a DFlash2 GGUF that azllm loads with ``-md``.

Example (one card, live features):
  python tools/dflash2_train/train.py --automodel PATH/Automodel \
      --target-gguf models/Qwen3.8-27B-Uncensored-TQ_L-GPTQ.gguf \
      --features-bin build/tqfeatures --drafter-gguf models/drafters/Qwen3.8-27B-DFlash2-TQ3.gguf \
      --data train.jsonl --out runs/dflash2 --steps 2000
"""

from __future__ import annotations

